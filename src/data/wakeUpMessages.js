function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function getWakeUpMessages(goals = [], dreams = [], count = 12) {
  const goalNames = goals.map((g) => g.name).filter(Boolean);
  const dreamTexts = dreams.map((d) => (typeof d === 'string' ? d : d.text)).filter(Boolean);
  const messages = new Set();

  while (messages.size < count) {
    if (goalNames.length && Math.random() > 0.2) {
      const goal = pick(goalNames);
      const pool = messages.size > count / 2 ? WAKE_BRUTAL : WAKE_GOAL;
      messages.add(pick(pool)(goal));
    } else if (dreamTexts.length && Math.random() > 0.4) {
      messages.add(pick(WAKE_DREAM)(pick(dreamTexts)));
    } else {
      messages.add(pick(GENERIC_WAKE));
    }
  }

  return [...messages];
}

export function getEscalatedMessage(goals, dreams, elapsedSeconds) {
  const goal = goals[0]?.name || 'твоей цели';
  if (elapsedSeconds >= 120) {
    return `2 МИНУТЫ ты лежишь как труп. «${goal}» мёртв. Через 30 лет ты будешь работать на работе, которую ненавидишь — потому что не смог встать СЕГОДНЯ. ВСТАВАЙ.`;
  }
  if (elapsedSeconds >= 60) {
    return `${Math.floor(elapsedSeconds / 60)} минут ты выбираешь быть никем. «${goal}» умирает. Через 30 лет — ненавистная работа и ненависть к себе. ВСТАВАЙ.`;
  }
  if (elapsedSeconds >= 30) {
    return `30 секунд слабости. «${goal}» или 30 лет рабства на чужой работе. Будильник не остановится.`;
  }
  return getWakeUpMessages(goals, dreams, 1)[0];
}
