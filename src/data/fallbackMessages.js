function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function getFallbackMessages(count, goals = [], dreams = []) {
  const goalNames = goals.map((g) => g.name).filter(Boolean);
  const dreamTexts = dreams.map((d) => (typeof d === 'string' ? d : d.text)).filter(Boolean);
  const messages = [];

  for (let i = 0; i < count; i++) {
    const roll = Math.random();
    if (goalNames.length && roll < 0.6) {
      messages.push(pick(BRUTAL_GOAL)(pick(goalNames)));
    } else if (dreamTexts.length && roll < 0.8) {
      messages.push(pick(BRUTAL_DREAM)(pick(dreamTexts)));
    } else {
      messages.push(pick(BRUTAL_GENERIC));
    }
  }

  return messages;
}

export const FALLBACK_MESSAGES = BRUTAL_GENERIC;
