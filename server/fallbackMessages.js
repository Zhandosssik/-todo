const BRUTAL_GOAL = [
  (g) =>
    `Ты сейчас не отдыхаешь — ты сливаешь жизнь. Открой «${g}» или через 30 лет будешь ненавидеть себя каждое утро перед работой, которую терпишь как раб.`,
  (g) =>
    `«${g}» — последний шанс не стать человеком, который в 50 лет пьёт и говорит «я мог бы». Ты уже на полпути к этому.`,
  (g) =>
    `Каждый раз, когда ты не делаешь «${g}», ты голосуешь за жизнь, где ты никто. Без права на уважение к себе.`,
  (g) =>
    `Пока ты лежишь, кто-то другой забирает твоё место в «${g}». Через 10 лет он будет жить твою мечту.`,
  (g) =>
    `«${g}» умирает прямо сейчас. Не завтра. Сейчас. Вместе с ней умирает версия тебя, которой можно было гордиться.`,
  (g) =>
    `Ты не устал. Ты трус. «${g}» — единственное, что отделяет тебя от приговора.`,
  (g) =>
    `«${g}» или 40 лет на работе, где тебя не уважают. Ты каждый день выбираешь второе.`,
];

const BRUTAL_DREAM = [
  (d) =>
    `«${d}» — или 30 лет на работе, которую ненавидишь, с лицом человека, который предал сам себя.`,
  (d) =>
    `Мечта «${d}» гниёт, пока ты выбираешь комфорт. Ты уже умираешь — медленно.`,
  (d) =>
    `«${d}» не для слабаков. А ты сейчас доказываешь, что слабак. Каждым «не сегодня».`,
];

const BRUTAL_GENERIC = [
  'Ты не ленивый — ты медленно убиваешь себя. Каждый день без действия — согласие на жизнь, которую ненавидишь.',
  'Через 30 лет ты будешь либо свободен, либо рабом. Сегодня ты снова выбираешь цепи.',
  'Твоё «потом» — кладбище мечт. Ты уже копаешь себе могилу.',
];

export function getServerFallbackMessages(goals, dreams, count) {
  const goalNames = goals.map((g) => g.name).filter(Boolean);
  const dreamTexts = dreams.map((d) => (typeof d === 'string' ? d : d.text)).filter(Boolean);
  const messages = [];

  for (let i = 0; i < count; i++) {
    if (goalNames.length && i % 3 !== 2) {
      messages.push(BRUTAL_GOAL[i % BRUTAL_GOAL.length](goalNames[i % goalNames.length]));
    } else if (dreamTexts.length) {
      messages.push(BRUTAL_DREAM[i % BRUTAL_DREAM.length](dreamTexts[i % dreamTexts.length]));
    } else {
      messages.push(BRUTAL_GENERIC[i % BRUTAL_GENERIC.length]);
    }
  }
  return messages;
}
